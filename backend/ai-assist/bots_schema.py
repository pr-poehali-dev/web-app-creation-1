TYPES = {"intraday": INTRADAY, "trend": TREND, "news": NEWS, "elliott": ELLIOTT, "abc": ABC}
RISK = {"intraday": (0.5, 2, 0.03), "trend": (1.0, 4, 0.03), "news": (0.5, 2, 0.04), "elliott": (1.0, 4, 0.03), "abc": (0.5, 4, 0.03)}
for _k, _v in RISK.items():
    TYPES[_k]["groups"].insert(0, risk_group(*_v))


def fields(bot_type: str) -> dict:
    out = {}
    for g in TYPES[bot_type]["groups"]:
        out.update(g["fields"])
    return out


def defaults(bot_type: str) -> dict:
    return {k: f["default"] for k, f in fields(bot_type).items()}


def sanitize(bot_type: str, raw) -> dict:
    out = defaults(bot_type)
    raw = raw if isinstance(raw, dict) else {}
    for k, f in fields(bot_type).items():
        if k not in raw or raw[k] is None or raw[k] == "":
            continue
        if f["t"] == "flag":
            out[k] = bool(raw[k])
        elif f["t"] == "select":
            if str(raw[k]) in [o[0] for o in f["options"]]:
                out[k] = str(raw[k])
        else:
            try:
                v = float(raw[k])
            except (TypeError, ValueError):
                continue
            v = min(max(v, f["min"]), f["max"])
            out[k] = int(round(v)) if f["int"] else v
    return out


def public_types() -> dict:
    return {k: {"title": v["title"], "desc": v["desc"], "timeframe": v["timeframe"], "groups": v["groups"], "defaults": defaults(k)}
            for k, v in TYPES.items()}
